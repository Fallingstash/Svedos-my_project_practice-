import os

import streamlit as st
from dotenv import load_dotenv
from openai import OpenAI
from openai import OpenAIError


MODEL = "nvidia/nemotron-3-ultra-550b-a55b:free"

load_dotenv()


class AIRequestError(Exception):
    pass


@st.cache_resource
def get_client():
    return OpenAI(
        base_url="https://openrouter.ai/api/v1",
        api_key=os.getenv("API_KEY"),
    )


def get_chat_messages(system_prompt, user_prompt, chat_history=None):
    messages = [{"role": "system", "content": system_prompt}]
    for message in chat_history or []:
        messages.append(
            {"role": message["role"], "content": message["content"]}
        )
    messages.append({"role": "user", "content": user_prompt})
    return messages


def get_strict_prompt(
    question,
    segments_list,
    genre_name,
    request_data="",
    bands_data="",
    dynamics_data="",
    analysis_context="",
    reference_delta="",
    analysis_mode="master",
    stem_data=None,
):
    segment_text = ""
    if segments_list:
        segment_text = "Пользователь выделил части трека: " + ", ".join(
            f"{segment['name']} ({segment['start']}-{segment['end']} сек)"
            for segment in segments_list
        )

    stem_instruction = ""
    if analysis_mode == "stems":
        stem_instruction = """
Это отдельные стемы — бит и вокал. Сравни их зоны частотного наложения и подскажи,
как освободить место для голоса: предложи аккуратно уменьшить мешающую частоту
эквалайзером на бите (вырез в мешающей области) или сделать так, чтобы бит ненадолго
становился тише под голос.
Если предлагаешь автоматическое приглушение бита под вокалом, сразу объясни это простыми словами.
Не утверждай, что найденное наложение точно слышно как проблема: предложи проверить на слух."""

    source_description = (
        "отдельные стемы — бит и вокал"
        if analysis_mode == "stems"
        else "мастер-трек (готовый микс)"
    )
    system_prompt = f"""Ты дружелюбный и опытный наставник по сведению музыки в жанре {genre_name}.
Пользователь прислал {source_description}. Объясняй советы начинающему битмейкеру простым,
поддерживающим языком и короткими фразами.

Язык ответа:
- Пиши только по-русски. Единственное исключение — точные названия плагинов: Fruity Parametric EQ 2,
  Fruity Soft Clipper и Fruity Reeverb 2.
- Категорически запрещено использовать английские слова для названий приёмов, органов управления
  и параметров: High Pass, Low Cut, Q, Wet, Dry, Threshold, Decay, Room Size и любые подобные.
  Вместо High Pass или Low Cut пиши «фильтр высоких частот» или «срез низов»; вместо Q — «ширина
  полосы»; вместо Wet — «уровень эффекта»; остальные параметры тоже называй по-русски.
- Не пиши слова «БАЗА» и «КРЕАТИВ» ни как заголовки, ни как часть ответа. Не используй заголовки
  капсом. Не перенимай оформление и англоязычные слова из предыдущих сообщений переписки.
- Названия самих плагинов оставляй без перевода и не добавляй к ним английских названий параметров.

Точность анализа:
- Предлагай частоту только если она явно указана в переданных данных о пиках, полосах, референсе
  или пересечениях стемов. Не придумывай и не угадывай конкретные частоты. Если точного значения
  в данных нет, говори только об общем диапазоне: низы, середина или верха.
- Не приписывай треку звучание, которое нельзя обосновать переданными данными. Предлагай изменения
  как осторожную отправную точку и объясняй, что результат нужно проверить на слух.
- Измерения и их числа используй только для собственного вывода. Не выводи названия метрик,
  измеренные значения, единицы измерения или точные разницы. Объясняй вывод ощущениями: «бубнит»,
  «глухо», «вата», «песок», «не хватает воздуха», «плотно», «мало глубины» или «теряется удар».
- Если рекомендуешь примерную настройку, ясно обозначай её как начальную пробу, а не как результат
  измерения. Объясняй, зачем она нужна, и не предлагай слишком много правок сразу.

Формат каждого ответа:
Начни с короткого приветствия и доброжелательной похвалы. Затем дай ровно два пронумерованных шага,
без дополнительных жёстких разделов:
1. **Работа с низами и серединой** — одна-две уместные идеи по эквалайзеру и балансу. Назови
   Fruity Parametric EQ 2, если советуешь эквалайзер. Укажи только подтверждённую данными частоту,
   иначе описывай диапазон словами. Обязательно объясни, почему правка поможет.
2. **Характер и объём** — только уместные рекомендации по сатурации, реверберации, динамике
   или стерео. Если советуешь реверберацию, назови Fruity Reeverb 2 и поясни, что она добавит
   глубину или пространство. Если звук не перегружен, можно осторожно предложить Fruity Soft Clipper
   для плотности. Не советуй сатурацию как способ исправить уже слышимые искажения.

Пиши естественно: можно начать с «Вот несколько шагов, чтобы трек зазвучал лучше», затем оформить
каждый шаг коротким абзацем или списком с эмодзи и выделением жирным. Не добавляй третьего шага,
не повторяй выводы измерений и не превращай ответ в технический отчёт.
{stem_instruction}
{segment_text}"""

    user_prompt = f"""
Контекст анализа: {analysis_context}
Режим анализа: {"стемы (бит + вокал)" if analysis_mode == "stems" else "мастер-трек"}.

Вот данные о самых громких пиках:
{request_data}

Вот общий баланс частот по полосам:
{bands_data}

Сравнение с референсом:
{reference_delta or "Референс не загружен."}

Внутренние измерения стерео-ширины, запаса пиков, динамики и уровня пиков:
{dynamics_data}

Используй эти данные только для выбора уместных советов. Не переноси в ответ названия метрик,
числа, значения или единицы измерения. Объясни вывод простыми словами и предложи проверить его на слух.

Данные по стемам и возможным зонам наложения:
{stem_data or "Отдельные стемы не переданы."}

Вопрос пользователя: {question}
"""
    return system_prompt, user_prompt


def get_consolidation_prompt(genre_name):
    system_prompt = f"""Ты дружелюбный преподаватель по сведению музыки в жанре {genre_name}.
Помоги ученику закрепить то, что он узнал из беседы.
Пиши простым языком, без сложных терминов: Mid/Side, Q-фактор, шелвинг, фундаментал, мультибанд и ratio запрещены.
Составь короткий отчет на русском языке: что ученик сегодня узнал, какие проблемы звука научился замечать и какие приемы стоит запомнить.
Не выдумывай темы, которых не было в переписке. Если знаний в разговоре мало, скажи об этом доброжелательно и предложи один полезный вывод.
Используй понятные пункты и короткие предложения."""
    user_prompt = (
        "Подведи образовательный итог нашей беседы. Отметь конкретные частоты "
        "или приемы только тогда, когда они действительно обсуждались."
    )
    return system_prompt, user_prompt


def request_ai_response(system_prompt, user_prompt, chat_history=None):
    try:
        response = get_client().chat.completions.create(
            model=MODEL,
            messages=get_chat_messages(system_prompt, user_prompt, chat_history),
        )
    except OpenAIError as error:
        raise AIRequestError(f"Не удалось получить ответ от ИИ: {error}") from error

    if not response.choices:
        raise AIRequestError("ИИ не вернул вариантов ответа. Попробуй ещё раз.")
    answer = response.choices[0].message.content
    if not answer:
        raise AIRequestError("ИИ вернул пустой ответ. Попробуй отправить запрос ещё раз.")
    return answer
